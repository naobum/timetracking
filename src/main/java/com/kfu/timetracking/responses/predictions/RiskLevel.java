package com.kfu.timetracking.responses.predictions;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Перечисление уровней риска невыполнения задания.
 * Используется для оценки опасности того, что студент не успеет выполнить задание к дедлайну.
 */
@Schema(description = "Уровень риска невыполнения задания вовремя")
public enum RiskLevel {
    /**
     * Безопасный уровень - достаточно времени, низкий риск неудачи.
     */
    @Schema(description = "Безопасный уровень - достаточно времени для выполнения задания")
    SAFE,
    
    /**
     * Низкий уровень - есть время, но нужно начинать работу.
     */
    @Schema(description = "Низкий уровень риска - есть время, но нужно начинать работу")
    LOW,
    
    /**
     * Средний уровень - ограниченное время, требуется активная работа.
     */
    @Schema(description = "Средний уровень риска - ограниченное время, требуется активная работа")
    MEDIUM,
    
    /**
     * Высокий уровень - очень мало времени, высокий риск неудачи.
     */
    @Schema(description = "Высокий уровень риска - очень мало времени, высокий риск неудачи")
    HIGH,
    
    /**
     * Критический уровень - почти нет времени, критический риск неудачи.
     */
    @Schema(description = "Критический уровень - почти нет времени, критический риск неудачи")
    CRITICAL
}
